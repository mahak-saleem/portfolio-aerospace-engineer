# essentially we wil write a code to find the derivative using a finite difference scheme
# we use a finite difference scheme
# mumerically the change in our x axis ( time) cannot be infinitesimal so it shoud be finite and solution becomes approximates
# therefore we have to define a finite value for the difference
# using a finite difference scheme since it gives us a more accurate numerical approximation  and is easier to calculate
# this is the formula to calculate and find the first derivatives from finite differences
# 
#   improved forward scheme (-f(x+2*h)+4*f(x+h)-3*f(x))/(2*h)
#                        or (-f(x[i+2])+4*f(x[i+1])-3*f(x[i]))/(x[i+2])-x[i])
# this is a higher order of accuracy as our change in time  - increases
# we would use forward scheme when for our intial power ( y axis ) and time (x axis)
# however both forward and backward scheme are generally more inaccurate then central scheme 

#   improved backward scheme (3*f(x)-4*f(x-h)+f(x-2*h))/(2*h)
#                       or (3*f(x[i])-4*f(x[i-1])+f(x[i-2]))/(x[i])-x[i-2])
#
#   improve central scheme (f(x+h)-f(x-h))/(2*h) or (f(x[i+1])-f(x[i-1]))/(x[i+1])-x[i-1])
