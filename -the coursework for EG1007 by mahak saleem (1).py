# Displacement function given in the question
def displacement(t): # here we first define our equation again 
    return 0.4 * np.sin(2*np.pi*t) * np.exp(-0.618*t)

# Velocity = derivative of displacement
def velocity(t): # we differentiate and get out velocity displacment 
    return (0.4 * np.exp(-0.618*t) *
            (2*np.pi*np.cos(2*np.pi*t) - 0.618*np.sin(2*np.pi*t)))

# Bisection method # here we are using this method to find out the time during the maximum displacement occurs 
def bisection(f, a, b, tol=1e-6): # tol = how accurate do we want the root - to how many signifcant figures etc 
    fa = f(a)  # both a and b is our initial guesses given in the equuation of 0 and 1 
    fb = f(b)

    if fa * fb > 0:
        raise ValueError("f(a) and f(b) must have opposite signs") # essentially if a and b are less then 0 one must be negative the other is a positive  - we exit the bisection method and loop if a and b create a value >0

    while abs(b - a) > tol: # abs = absolute value and we are saying distance between a and b ignoring whether the sign is positive or negative. so keep iterating until the distance of b-a is less then the total 
        c = (a + b) / 2 # c = our midpoint and we define our function 
        fc = f(c)

        if fa * fc < 0: # if our midpoint is greater then 0
            b, fb = c, fc # we swap b with c since c is closer to the maximum displacement
        else:
            a, fa = c, fc # we replace c with a if a multiplied by c is less then 0 

    return (a + b) / 2 #otherwirse we take our midpoint as our root 


